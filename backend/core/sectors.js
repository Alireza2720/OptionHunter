    'بساما':       'دارو',
    'سینرژی':      'دارو',

    // شیمیایی / پالایش
    'شپنا':        'پالایش',
    'دزاگرس':      'شیمیایی',
    'کاریس':       'شیمیایی',

    // فلزات
    'فملی':        'فلزات',
