    'اهرم':        'سرمایه‌گذاری',
    'شستا':        'سرمایه‌گذاری',
    'تاصیکو':      'سرمایه‌گذاری',
    'جوانه کوچک':  'سرمایه‌گذاری',

    // بانک
    'وتجارت':      'بانک',
    'وبصادر':      'بانک',
    'وبملت':       'بانک',
    'موج':         'بانک',

    // خودرو
    'خودرو':       'خودرو',
    'خبهمن':       'خودرو',
    'خساپا':       'خودرو',

    // دارو
    'هم تراز':     'دارو',
